-- 3.Join orders, order_items, and products to display detailed line items. 
select * from orders as o
inner join order_items as oi
on o.order_id=oi.order_id
inner join products as p
on p.product_id=oi.order_id;

-- 4.Write a query to group sales (total_price) by each store_id. 

select s.store_id, sum(oi.total_price) as total_sale
from order_items as oi
join orders as o
on o.order_id=oi.order_id
join stores as s
on s.store_id=o.store_id
group by s.store_id;

-- 5. Use ORDER BY and LIMIT to get the top 5 most sold products by quanttity.

select p.product_name,oi.product_id,sum(oi.quantity) as total_quantity
from order_items oi
inner join products p
on oi.product_id=p.product_id
group by p.product_name,oi.product_id
order by total_quantity desc limit 5;

