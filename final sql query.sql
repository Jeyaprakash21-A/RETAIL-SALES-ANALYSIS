-- 8. Analyze total revenue generated by each staff member based on their handled orders. 

select s.staff_id,round(sum(oi.total_price)) as total_revenue
from orders o
inner join staffs s
on s.staff_id=o.staff_id
inner join order_items oi
on o.order_id=oi.order_id
group by s.staff_id;

-- 9. Write a query to list products where stock quantity < 10 in any store. 

select p.product_id,s.store_name, sum(oi.quantity) as total_quantity
from products p
inner join order_items oi
on p.product_id=oi.product_id
inner join orders o 
on o.order_id=oi.order_id
inner join stores s
on o.store_id=s.store_id
group by p.product_id,s.store_name
